function syncModalConfig(step, modal) {
  step.config = step.config || {};
  modal.querySelectorAll('[data-key]').forEach(el => {
    step.config[el.dataset.key] = el.value;
  });
  stSave();
}

function renderConnections(svgEl, steps) {
  svgEl.innerHTML = '';
  for (let i = 1; i < steps.length; i++) {
    const from = steps[i - 1];
    const to = steps[i];
    if (!from._x || !to._x) continue;

    const fx = from._x + NODE_W;
    const fy = from._y + NODE_H / 2;
    const tx = to._x;
    const ty = to._y + NODE_H / 2;
    const cx1 = fx + Math.abs(tx - fx) * 0.4;
    const cx2 = tx - Math.abs(tx - fx) * 0.4;
    const path = `M${fx},${fy} C${cx1},${fy} ${cx2},${ty} ${tx},${ty}`;

    const cls = BP.stairsOutputs[from.id]?.ok ? 'st-connection done' : 'st-connection';
    const pathEl = document.createElementNS('http://www.w3.org/2000/svg', 'path');
    pathEl.setAttribute('d', path);
    pathEl.setAttribute('class', cls);
    svgEl.appendChild(pathEl);

    const arrow = document.createElementNS('http://www.w3.org/2000/svg', 'polygon');
    arrow.setAttribute('points', `${tx - 8},${ty - 4} ${tx},${ty} ${tx - 8},${ty + 4}`);
    arrow.setAttribute('class', 'st-connection-arrow');
    svgEl.appendChild(arrow);
  }
}

function initNodeDrag(nodesEl) {
  nodesEl.querySelectorAll('.st-node').forEach(node => {
    let dragging = false, ox = 0, oy = 0;
    node.addEventListener('mousedown', e => {
      if (e.target.closest('button,textarea,input,select,[contenteditable]')) return;
      dragging = true;
      ox = e.clientX - parseInt(node.style.left);
      oy = e.clientY - parseInt(node.style.top);
      node.classList.add('dragging');
      e.preventDefault();
    });
    window.addEventListener('mousemove', e => {
      if (!dragging) return;
      node.style.left = `${e.clientX - ox}px`;
      node.style.top = `${e.clientY - oy}px`;
    });
    window.addEventListener('mouseup', () => {
      if (!dragging) return;
      dragging = false;
      node.classList.remove('dragging');
      const step = BP.stairsCurrent?.steps.find(s => s.id === node.dataset.id);
      if (step) {
        step._x = parseInt(node.style.left);
        step._y = parseInt(node.style.top);
        stSave();
      }
      const svgEl = stEl('stCanvasSvg');
      if (svgEl) renderConnections(svgEl, BP.stairsCurrent?.steps || []);
    });
  });
}

function initMiniToolbar() {
  stEl('stMiniAdd')?.addEventListener('click', () => {
    stEl('stStepTypeMenu').classList.toggle('hidden');
  });

  const zi = stEl('stMiniZoomIn');
  if (zi) { zi.onclick = null; zi.addEventListener('click', () => zoomIn()); }

  const zo = stEl('stMiniZoomOut');
  if (zo) { zo.onclick = null; zo.addEventListener('click', () => zoomOut()); }

  const zf = stEl('stMiniFit');
  if (zf) {
    zf.onclick = null;
    zf.addEventListener('click', () => {
      const nodesEl = stEl('stCanvasNodes');
      const nodeList = nodesEl?.querySelectorAll('.st-node');
      if (nodeList?.length) fitToView(nodeList);
    });
  }
}

