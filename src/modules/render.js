let saveTimer = null;
const SAVE_DEBOUNCE = 500;

export function stSave() {
  if (saveTimer) clearTimeout(saveTimer);
  saveTimer = setTimeout(() => doSave(), SAVE_DEBOUNCE);
}

function stSaveImmediate() {
  if (saveTimer) clearTimeout(saveTimer);
  doSave();
}

async function doSave() {
  if (!BP.stairsCurrent) return;
  BP.stairsCurrent.name = stEl('stName').value.trim() || 'Untitled';
  await window.buildpipe.saveStaircase(BP.stairsCurrent);
  stLoadAll();
}

export async function stLoadAll() {
  let all = await window.buildpipe.listStaircases();
  const hasSample = all.find(s => s.id === ST_SAMPLE.id);
  if (!hasSample || (hasSample.version || 0) < ST_SAMPLE.version) {
    await window.buildpipe.saveStaircase(ST_SAMPLE);
    all = await window.buildpipe.listStaircases();
  }
  const list = stEl('stProjectList');
  if (!list) return;
  list.innerHTML = '';
  if (!all.length) {
    list.innerHTML = '<div style="padding:16px 14px;font-size:12px;opacity:0.35;">No pipelines yet</div>';
    return;
  }
  for (const sc of all) {
    const el = document.createElement('div');
    el.className = `st-project-item${sc.status === 'published' ? ' published' : ''}`;
    el.dataset.id = sc.id;
    el.innerHTML = `<span class="st-proj-dot"></span><span class="st-project-name-text">${sc.name || 'Untitled'}</span>`;
    el.addEventListener('click', () => stOpen(sc));
    list.appendChild(el);
  }
  if (all.length === 1 && !BP.stairsCurrent) {
    // Don't auto-open — dashboard is the default view
  }

  BP.updateUndoButtons();
}

export function stOpen(sc) {
  try {
    BP.stairsCurrent = JSON.parse(JSON.stringify(sc));
    BP.stairsOutputs = {};
    stEl('stName').value = sc.name || '';
    const published = sc.status === 'published';
    stEl('stDraftBadge').classList.toggle('hidden', published);
    stEl('stPublishedBadge').classList.toggle('hidden', !published);
    document.querySelectorAll('.st-project-item').forEach(el => {
      el.classList.toggle('active', el.dataset.id === sc.id);
    });
    showEditor();
    stRenderCanvas();
    stLoadLog();
    BP.pushUndo();
    BP.updateUndoButtons();
  } catch (e) {
    stLog(`Error opening pipeline: ${e.message}`, 'log-error');
  }
}

export function stRenderCanvas() {
  const canvas = stEl('stCanvas');
  const nodesEl = stEl('stCanvasNodes');
  const svgEl = stEl('stCanvasSvg');
  const emptyEl = stEl('stEmpty');
  const toolbar = stEl('stMiniToolbar');
  if (!canvas || !nodesEl || !svgEl) return;

  const steps = BP.stairsCurrent?.steps || [];
  const isCanvas = BP.viewMode === 'horizontal';

  destroyCanvas();

  if (isCanvas) {
    canvas.classList.remove('vertical-list');
    nodesEl.classList.remove('vertical-list');
    canvas.style.display = '';
    canvas.style.flexDirection = '';
    canvas.style.overflow = 'hidden';
    nodesEl.style.transform = '';
    nodesEl.style.position = 'absolute';
    nodesEl.style.flex = '';
    nodesEl.style.overflow = '';
    svgEl.style.display = '';
    if (toolbar) toolbar.style.display = 'flex';
    const wrap = canvas.parentElement;
    if (wrap) wrap.style.overflow = 'hidden';
  } else {
    nodesEl.classList.add('vertical-list');
    canvas.style.display = 'flex';
    canvas.style.flexDirection = 'column';
    canvas.style.overflow = '';
    nodesEl.style.transform = 'none';
    nodesEl.style.position = '';
    nodesEl.style.overflow = 'auto';
    nodesEl.style.flex = '1';
    svgEl.style.display = 'none';
    if (toolbar) toolbar.style.display = 'none';
    const wrap = canvas.parentElement;
    if (wrap) wrap.style.overflow = 'visible';
  }

  nodesEl.innerHTML = '';
  svgEl.innerHTML = '';

  if (!steps.length) {
    if (emptyEl) emptyEl.style.display = '';
    if (isCanvas) initCanvas(canvas);
    return;
  }

  if (emptyEl) emptyEl.style.display = 'none';

  if (isCanvas) {
    positionNodes(steps);
    steps.forEach((step, i) => {
      nodesEl.appendChild(stBuildNode(step, i));
    });
    renderConnections(svgEl, steps);
    initNodeDrag(nodesEl);
    initMiniToolbar();
    initCanvas(canvas);
    setTimeout(() => {
      const nodeList = nodesEl.querySelectorAll('.st-node');
      if (nodeList.length) fitToView(nodeList);
    }, 100);
  } else {
    steps.forEach((step, i) => {
      if (i > 0) {
        const conn = document.createElement('div');
        conn.className = 'st-connector';
        conn.innerHTML = '<div class="st-connector-dot"></div>';
        nodesEl.appendChild(conn);
      }
      nodesEl.appendChild(stBuildVerticalCard(step, i));
    });
  }

  for (const [id, res] of Object.entries(BP.stairsOutputs)) {
    stApplyStepOutput(id, res);
  }

  if (!isCanvas) {
    initDragDrop({ onSave: stSave, onRender: stRenderCanvas });
  }
}

const NODE_W = 240;
const NODE_H = 80;
const GAP_X = 100;
const GAP_Y = 80;

function positionNodes(steps) {
  const cols = Math.min(3, steps.length);
  steps.forEach((step, i) => {
    if (!step._x || !step._y) {
      const col = i % cols;
      const row = Math.floor(i / cols);
      step._x = col * (NODE_W + GAP_X);
      step._y = row * (NODE_H + GAP_Y);
    }
  });
}

